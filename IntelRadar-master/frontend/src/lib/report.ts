import { METRICS, formatScannedAt, type Competitor } from "./dashboard";

const NONE = "—";

const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "competitor";

/** Escape pipes/newlines so values survive a Markdown table cell. */
const cell = (value: unknown) =>
  String(value ?? NONE)
    .replace(/\|/g, "\\|")
    .replace(/\s*\n+\s*/g, " ")
    .trim() || NONE;

const bullets = (items?: string[]) =>
  items?.length ? items.map((item) => `- ${item}`).join("\n") : "- None recorded";

/**
 * A complete, consultant-friendly teardown of one competitor. Plain Markdown
 * so it drops into Notion, GitHub, email, or any Markdown-to-PDF tool.
 */
export function competitorToMarkdown(competitor: Competitor): string {
  const c = competitor;
  const metrics = METRICS.map((metric) => ({
    label: metric.label,
    value: c.radar_metrics?.[metric.key],
  })).filter((row) => typeof row.value === "number");

  const lines: string[] = [
    `# ${c.competitor_name} — Competitive intelligence`,
    "",
  ];

  if (c.tagline) lines.push(`> ${c.tagline}`, "");

  lines.push(
    "| Field | Detail |",
    "| --- | --- |",
    `| Market segment | ${cell(c.segment || c.category)} |`,
    `| Category | ${cell(c.category)} |`,
    `| Threat level | ${cell(c.threat_level)} |`,
    `| Threat score | ${cell(c.threat_score)} / 100 |`,
    `| Last scanned | ${cell(formatScannedAt(c.last_scanned_at))} |`,
    `| Website | ${cell(c.target_url)} |`,
    ""
  );

  lines.push("## Strategic brief", "", c.strategic_summary || "No summary recorded.", "");

  lines.push("## Where to compete", "", bullets(c.vulnerabilities_to_exploit), "");

  if (metrics.length) {
    lines.push("## Threat signals", "", "| Signal | Score (0–100) |", "| --- | --- |");
    for (const metric of metrics) {
      lines.push(`| ${cell(metric.label)} | ${cell(metric.value)} |`);
    }
    lines.push("");
  }

  if (c.pricing_tiers?.length) {
    lines.push("## Pricing", "");
    for (const tier of c.pricing_tiers) {
      lines.push(
        `### ${cell(tier.plan)} — ${cell(tier.price)}${
          tier.billing_period ? ` / ${cell(tier.billing_period)}` : ""
        }`,
        ""
      );
      lines.push(...(tier.highlights?.length ? tier.highlights.map((h) => `- ${h}`) : ["- No inclusions listed"]), "");
    }
  }

  if (c.key_features?.length) {
    lines.push(
      "## Key features",
      "",
      "| Feature | Category | Maturity | Why it matters |",
      "| --- | --- | --- | --- |"
    );
    for (const feature of c.key_features) {
      lines.push(
        `| ${cell(feature.feature)} | ${cell(feature.category)} | ${cell(
          feature.maturity
        )} | ${cell(feature.strategic_edge)} |`
      );
    }
    lines.push("");
  }

  const swot = c.swot_analysis;
  if (swot) {
    lines.push("## SWOT", "");
    for (const [title, key] of [
      ["Strengths", "strengths"],
      ["Weaknesses", "weaknesses"],
      ["Opportunities", "opportunities"],
      ["Threats", "threats"],
    ] as const) {
      lines.push(`### ${title}`, "", bullets(swot[key]), "");
    }
  }

  if (c.customer_complaints?.length) {
    lines.push("## Customer complaints", "");
    for (const complaint of c.customer_complaints) {
      lines.push(
        `- **${cell(complaint.severity)}** — ${complaint.issue}${
          complaint.source ? ` (${complaint.source})` : ""
        }`
      );
    }
    lines.push("");
  }

  if (c.recent_news?.length) {
    lines.push("## Recent signals", "");
    for (const item of c.recent_news) {
      const meta = [item.source, item.published].filter(Boolean).join(", ");
      lines.push(`- [${item.title}](${item.url})${meta ? ` — ${meta}` : ""}`);
    }
    lines.push("");
  }

  if (c.recent_movements?.length) {
    lines.push("## Recent moves", "");
    for (const move of c.recent_movements) {
      const meta = [move.date, move.type].filter(Boolean).join(" · ");
      lines.push(`- ${meta ? `**${meta}** — ` : ""}${move.headline}. ${move.impact}`.trim());
    }
    lines.push("");
  }

  if (c.changes?.length) {
    lines.push("## Changes since last scan", "");
    for (const change of c.changes) {
      lines.push(`- **${cell(change.severity)}** — ${change.summary}`);
    }
    lines.push("");
  }

  lines.push(
    "---",
    "",
    `Generated by IntelRadar on ${new Date().toISOString().slice(0, 10)}.`
  );

  return lines.join("\n");
}

/** Trigger a browser download of the Markdown report. */
export function downloadCompetitorReport(competitor: Competitor): void {
  const blob = new Blob([competitorToMarkdown(competitor)], {
    type: "text/markdown;charset=utf-8",
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${slugify(competitor.competitor_name)}-intelradar-report.md`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
